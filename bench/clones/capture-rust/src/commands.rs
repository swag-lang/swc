    pub fn group(self) -> &'static str {
        use Command::*;
        match self {
            Tool(_) => "Tools",
            CaptureArea | CaptureScreen | CaptureWindow | CaptureLast => "Capture",
            Undo | Redo | Copy | Cut | Paste | Duplicate | Delete | SelectAll | Deselect
            | InvertSelection | Group | Ungroup | Freeze | Front | Back | Forward | Backward
            | AlignLeft | AlignCenter | AlignRight | AlignTop | AlignMiddle | AlignBottom
            | ResetSteps => "Selection",
            New | Open | Save | Export | CopyImage | PasteImage | Flatten | Crop | Resize
            | RotateLeft | RotateRight | Mirror | Flip | Restore | Favorite => "Image",
            Library | OpenSelected | ChooseLibrary => "Library",
            ZoomIn | ZoomOut | ActualSize | Fit | Inspector => "View",
            _ => "Application",
        }
    }

